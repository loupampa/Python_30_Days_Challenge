# Python Error Types - Day 15
# SyntaxError: Sometimes this happens when we forgot to enclose the string
## with parenthesis and Python already suggests the solution

# NameError: Sometimes this happens when we don't define a variable and we try to print it.
## Python suggests the solution to define the variable first.

# IndexError: This happens when we try to access an index that is out of range in a list or string.
## like trying to access the 5th element of a list that only has 3 elements.

# ModuleNotFoundError: This happens when we try to import a module that doesn't exist or is not installed.
## Python suggests the solution to install the module first.

# AttributeError: This happens when we try to access an attribute or method that doesn't exist for a particular object.
## Python suggests the solution to check the object type and see if the attribute or method exists.

# KeyError: This happens when we try to access a key that doesn't exist in a dictionary.
## Python suggests the solution to check if the key exists before accessing it.

# TypeError: This happens when we try to perform an operation on a data type that is not compatible with that operation.
## Python suggests the solution to check the data types and make sure they are compatible.

# ImportError: This happens when we try to import a module that is not found in the current directory or in the Python path.
## Python suggests the solution to check the Python path and make sure the module is installed.

# ValueError: This happens when we try to perform an operation on a value that is not valid for that operation.

